/**
 * @vitest-environment jsdom
 */
import { afterEach, describe, expect, it } from "vitest";
import { cleanup, render, screen, within } from "@testing-library/react";
import { LanguageProvider } from "@/lib/i18n";
import { REPORT_CONTENT_FIELDS } from "./report-document-view";
import type { ConsistencyBlock } from "@/lib/report-consistency";
import { PrintableReport } from "./printable-report";

const CONTENT = {
  examination: "Chest X-ray",
  clinical_history: "Cough for three weeks",
  technique: "Posteroanterior (PA) chest X-ray",
  findings: "Bilateral lower lobe airspace opacities.",
  impression: "Findings consistent with bilateral pneumonia.",
  recommendation: "Correlate clinically and consider follow-up imaging.",
  disclaimer: "This report was generated by an AI assistant and requires review.",
};

const BASE = {
  report_id: "abc123",
  report_date: "2026-09-22",
  status: "ai_draft",
  language: "en",
  content: CONTENT,
  validation: { is_clean: true, warnings: [] as string[] },
  consistency: {
    status: "clean",
    checks_run: ["temporal"],
    applicable_checks: ["temporal"],
    violations: [],
  } as ConsistencyBlock,
  finalized_at: null as string | null,
};

function show(overrides: Partial<typeof BASE> = {}, finalizedByName: string | null = null) {
  return render(
    <LanguageProvider initial="en">
      <PrintableReport
        report={{ ...BASE, ...overrides }}
        patientName="Aisha Rahman"
        patientCode="PAT-000043"
        finalizedByName={finalizedByName}
      />
    </LanguageProvider>,
  );
}

const root = (c: HTMLElement) => c.querySelector(".rr-print-root") as HTMLElement;
const sections = (c: HTMLElement) =>
  [...c.querySelectorAll("[data-print-section]")].map((el) => el.getAttribute("data-print-section"));

afterEach(cleanup);

describe("Printed report — every section, in order, unconditionally", () => {
  it("prints all seven content sections", () => {
    const { container } = show();
    const printed = sections(container);
    for (const { key } of REPORT_CONTENT_FIELDS) {
      expect(printed, `expected ${key} on the printed page`).toContain(key);
    }
  });

  it("prints them in the canonical order, not the screen's summary-first order", () => {
    // The workspace leads with impression and recommendation and hides the
    // other five behind a disclosure. Paper is a document, so it follows the
    // reading order a radiologist expects.
    const { container } = show();
    const printed = sections(container).filter((k) =>
      REPORT_CONTENT_FIELDS.some((f) => f.key === k),
    );
    expect(printed).toEqual(REPORT_CONTENT_FIELDS.map((f) => f.key));
  });

  it("carries the body text of every section", () => {
    const { container } = show();
    for (const value of Object.values(CONTENT)) {
      expect(root(container).textContent).toContain(value);
    }
  });

  it("has no way to be told the screen collapsed something", () => {
    // The guarantee is structural: there is no prop that could hide a section,
    // so no UI state can reach the printout. If someone adds one, this fails.
    const props = PrintableReport.length;
    expect(props).toBe(1); // a single props object
    const { container } = show();
    expect(sections(container).length).toBeGreaterThanOrEqual(REPORT_CONTENT_FIELDS.length);
  });
});

describe("Printed report — the study identification header", () => {
  it("names the system, the patient, the study date and the status", () => {
    const { container } = show();
    const text = root(container).textContent ?? "";
    expect(text).toContain("RadAssist-RAG");
    expect(text).toContain("Aisha Rahman");
    expect(text).toContain("PAT-000043");
    expect(text).toContain("2026-09-22");
    expect(text).toContain("AI Draft");
  });

  it("says so rather than blanking when the patient is not recorded", () => {
    const { container } = render(
      <LanguageProvider initial="en">
        <PrintableReport report={BASE} patientName={null} patientCode={null} finalizedByName={null} />
      </LanguageProvider>,
    );
    expect(root(container).textContent).toContain("Not recorded");
  });
});

describe("Printed report — warnings and the consistency verdict always print", () => {
  it("prints validation warnings", () => {
    const { container } = show({
      validation: { is_clean: false, warnings: ["Mentions 'Pleural Effusion' which is not supported"] },
    });
    const block = container.querySelector('[data-print-section="validation"]') as HTMLElement;
    expect(block).not.toBeNull();
    expect(within(block).getByText(/Pleural Effusion/)).not.toBeNull();
  });

  it("prints the validation block even when it is clean", () => {
    // Absence would be read as "no problems" by a reader who cannot tell it
    // from "not checked" -- the same rule the screen follows.
    const { container } = show();
    const block = container.querySelector('[data-print-section="validation"]') as HTMLElement;
    expect(block.textContent).toContain("No validation warnings");
  });

  const states: [string, ConsistencyBlock, string][] = [
    ["clean", { status: "clean", checks_run: ["temporal"], applicable_checks: ["temporal"], violations: [] }, "Checks passed"],
    ["partial", { status: "partial", checks_run: ["temporal"], applicable_checks: ["temporal", "transplant"], violations: [] }, "Partially checked"],
    ["violations", { status: "violations", checks_run: ["temporal"], applicable_checks: ["temporal"], violations: [{ check: "t", severity: "error", field: "impression", detail: "d" }] }, "Issues found"],
    ["not_run", { status: "not_run", checks_run: [], applicable_checks: [], violations: [] }, "Checks not run"],
  ];

  for (const [label, consistency, expected] of states) {
    it(`prints the consistency verdict for ${label}`, () => {
      const { container } = show({ consistency });
      const block = container.querySelector('[data-print-section="consistency"]') as HTMLElement;
      expect(block.textContent).toContain(expected);
    });
  }

  it("prints the Bengali reason for a Bengali report that was not checked", () => {
    const { container } = show({
      language: "bn",
      consistency: { status: "not_run", checks_run: [], applicable_checks: [], violations: [] },
    });
    const block = container.querySelector('[data-print-section="consistency"]') as HTMLElement;
    expect(block.textContent).toContain("not available for Bengali reports");
  });

  it("marks the document's language so the right font is applied", () => {
    const { container } = show({ language: "bn" });
    expect(root(container).getAttribute("lang")).toBe("bn");
  });
});

describe("Printed report — the signature block", () => {
  it("prints the finalizing doctor and date on a final report", () => {
    const { container } = show(
      { status: "final", finalized_at: "2026-09-22T10:00:00" },
      "Dr Sumaiyah Khan",
    );
    const block = container.querySelector('[data-print-section="finalized"]') as HTMLElement;
    expect(block).not.toBeNull();
    expect(block.textContent).toContain("Dr Sumaiyah Khan");
  });

  it("prints no signature on a draft", () => {
    // A draft is explicitly not a signed document; a name under one would say
    // otherwise on a page that outlives the screen.
    const { container } = show();
    expect(container.querySelector('[data-print-section="finalized"]')).toBeNull();
  });
});

describe("Printed report — no UI chrome", () => {
  it("contains no controls of any kind", () => {
    const { container } = show({ validation: { is_clean: false, warnings: ["w"] } });
    const doc = root(container);
    for (const tag of ["button", "nav", "a", "input", "select", "textarea"]) {
      expect(doc.querySelectorAll(tag).length, `expected no <${tag}> on paper`).toBe(0);
    }
  });

  it("exposes no interactive roles", () => {
    show();
    expect(screen.queryAllByRole("button")).toHaveLength(0);
    expect(screen.queryAllByRole("tab")).toHaveLength(0);
    expect(screen.queryAllByRole("link")).toHaveLength(0);
  });
});
